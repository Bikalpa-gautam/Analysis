"""HTML verification report: benchmarks and cross-checks."""
from __future__ import annotations

import datetime as _dt
import html
import platform

import numpy as np

from .. import __version__
from ..report.html import CSS, mk, num, pill


def render(results, crosschecks=None) -> str:
    n_b = len(results)
    comps = [c for _, cs, _ in results for c in cs]
    n_pass = sum(c.passed for c in comps)
    errors = [(b, e) for b, _, e in results if e]
    ok = n_pass == len(comps) and not errors and all(cs for _, cs, _ in results)
    today = _dt.date.today().isoformat()
    out = [f"<!doctype html><html lang='en'><head><meta charset='utf-8'><meta name='viewport' content='width=device-width,initial-scale=1'>"
           f"<title>Tragwerk {__version__} verification</title><style>{CSS}</style></head><body><div class='page'>"]
    out.append(
        f"<header class='top'><div><p class='kicker'>Software verification</p><h1>Tragwerk {__version__}</h1>"
        f"<div class='meta'>{today} · Python {platform.python_version()} · NumPy {np.__version__}</div></div>"
        f"<div class='verdict'><div class='lab'>Comparisons passed</div><div class='big' style='color:{'var(--pass)' if ok else 'var(--fail)'}'>{n_pass}/{len(comps)}</div>"
        f"<div style='margin-top:6px'>{pill('pass' if ok else 'fail')}</div><div class='meta'>{n_b} benchmarks</div></div></header>")
    out.append("<p>Every benchmark compares a result of this build with a closed-form solution, a published table or a hand "
               "calculation. Expected values are computed from the reference formula and never by the code under test. "
               "The suite runs on every release; a single failure blocks the release.</p>")
    cats: dict[str, list] = {}
    for bm, cs, err in results:
        cats.setdefault(bm.category, []).append((bm, cs, err))
    for k, (cat, items) in enumerate(cats.items(), 1):
        out.append(f"<h2><span class='n'>{k}</span>{html.escape(cat)}</h2>")
        for bm, cs, err in items:
            st = "fail" if err or not cs or not all(c.passed for c in cs) else "pass"
            rows = []
            for c in cs:
                tol = f"{c.rel_tol:.0e} rel" if c.rel_tol * abs(c.expected) >= c.abs_tol else f"{c.abs_tol:g} abs"
                rows.append(f"<tr><td>{mk(c.quantity)}</td><td class='num'>{num(c.computed)}</td><td class='num'>{num(c.expected)}</td>"
                            f"<td>{mk(c.unit)}</td><td class='num'>{c.rel_error:.1e}</td><td class='num'>{tol}</td><td>{pill('pass' if c.passed else 'fail')}</td></tr>")
            out.append(f"<div class='check'><div class='hd'><h4>{html.escape(bm.id)} · {html.escape(bm.title)}</h4>{pill(st)}</div>"
                       f"<div class='where'>Reference: {mk(bm.reference)}</div>"
                       + (f"<div class='callout'>{html.escape(err)}</div>" if err else "")
                       + "<table><thead><tr><th>Quantity</th><th class='num'>Tragwerk</th><th class='num'>Reference</th><th>Unit</th>"
                         "<th class='num'>Rel. error</th><th class='num'>Tolerance</th><th></th></tr></thead><tbody>"
                       + "".join(rows) + "</tbody></table></div>")
    if crosschecks:
        k = len(cats) + 1
        out.append(f"<h2><span class='n'>{k}</span>Cross-check against independent solvers</h2>")
        out.append("<p>Randomly generated multi-bay, multi-storey frames (fixed and pinned bases, hinges, uniform, partial, "
                   "trapezoidal and point loads, lateral loads) are solved by Tragwerk and by an independent program. "
                   "The table gives the largest difference relative to the largest value of each quantity.</p>")
        rows = []
        for r in crosschecks:
            good = r["displacement"] < 1e-9 and r["reaction"] < 1e-9 and (r["moment"] is None or r["moment"] < 1e-6)
            rows.append(f"<tr><td>{html.escape(r['solver'])}</td><td class='num'>{r['seed']}</td><td class='num'>{r['nodes']}</td>"
                        f"<td class='num'>{r['members']}</td><td class='num'>{r['hinges']}</td><td class='num'>{r['displacement']:.1e}</td>"
                        f"<td class='num'>{r['reaction']:.1e}</td><td class='num'>{'–' if r['moment'] is None else f'{r['moment']:.1e}'}</td>"
                        f"<td>{pill('pass' if good else 'fail')}</td></tr>")
        out.append("<table><thead><tr><th>Solver</th><th class='num'>Frame</th><th class='num'>Nodes</th><th class='num'>Members</th>"
                   "<th class='num'>Hinges</th><th class='num'>Displacements</th><th class='num'>Reactions</th><th class='num'>Moments</th><th></th></tr></thead><tbody>"
                   + "".join(rows) + "</tbody></table>")
        out.append("<p class='muted'>PyNite is MIT-licensed. OpenSees is used only as a development-time test oracle.</p>")
    out.append(f"<footer>Generated by <code>tragwerk verify</code> on {today}.</footer></div></body></html>")
    return "".join(out)
